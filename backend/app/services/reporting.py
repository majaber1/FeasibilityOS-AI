"""
Feasibility report generation (PDF via reportlab, Word via python-docx).

Both generators return raw bytes so the API layer can stream them without
touching the filesystem. Bilingual: locale "ar" renders Arabic labels and
right-alignment; "en" renders English. Arabic glyph shaping is applied when
arabic_reshaper + python-bidi are available and gracefully degrades to
unshaped text otherwise, so report generation never hard-fails on a slim runtime.

No invented numbers: every figure comes from the persisted study/result. Missing
values are rendered as a dash rather than fabricated.
"""
